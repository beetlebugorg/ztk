fn inTable(table: []const Range, cp: u21) bool {
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {
        const mid = (lo + hi) / 2;
        if (cp < table[mid][0]) {
            hi = mid;
        } else if (cp > table[mid][1]) {
            lo = mid + 1;
        } else return true;
    }
    return false;
}

pub fn of(cp: u21) u2 {
    if (cp < 0x300) return 1;
    if (inTable(&zero, cp)) return 0;
    if (inTable(&wide, cp)) return 2;
    return 1;
}

test "the width of code points" {
    try std.testing.expectEqual(@as(u2, 1), of('a'));
    try std.testing.expectEqual(@as(u2, 1), of(0x2500));
    try std.testing.expectEqual(@as(u2, 2), of(0x4e2d));
    try std.testing.expectEqual(@as(u2, 2), of(0x1f600));
    try std.testing.expectEqual(@as(u2, 0), of(0x0301));
    try std.testing.expectEqual(@as(u2, 0), of(0xfe0f));
    for (zero[1..], 0..) |r, k| try std.testing.expect(r[0] > zero[k][1]);
    for (wide[1..], 0..) |r, k| try std.testing.expect(r[0] > wide[k][1]);
}
