//! The column width of a code point in a terminal: 0, 1, or 2. The
//! ranges are a short form of the East Asian Width property (W and F)
//! and of the general categories Mn, Me, and Cf of the Unicode Character
//! Database, as `wcwidth` gives them. Each table is sorted, and a binary
//! search finds the range. The terminal drops a code point of width 0:
//! it keeps no combining marks in this version.
//! SPDX-License-Identifier: BSD-2-Clause

